type F = Formatters;

/** Alternatives joined with "or": "“A”, “B” or “C”". */
const orList = (values: readonly string[], or: string): string =>
  values.length <= 1
    ? (values[0] ?? "")
    : `${values.slice(0, -1).join(", ")} ${or} ${values.at(-1) ?? ""}`;

/** "Jonas's", "Kids'": English possessives. */
const possessiveEn = (name: string): string => (/s$/iu.test(name) ? `${name}'` : `${name}'s`);

/** "Jonas'", "Maras": German possessives (an apostrophe after s, x and z). */
const possessiveDe = (name: string): string => (/[sxzß]$/iu.test(name) ? `${name}'` : `${name}s`);

